#!/usr/bin/env bash
# Local, per-worktree Redis and optional direct web-port allocation.
# This file is sourced after _common.sh. Bash 3.2 compatible.

_gitwo_runtime_root() { printf '%s/runtime\n' "$GITWO_STATE"; }
_gitwo_runtime_dir() { printf '%s/%s\n' "$(_gitwo_runtime_root)" "$(basename "$1")"; }
_gitwo_runtime_ports_file() { printf '%s/%s.ports\n' "$(_gitwo_runtime_root)" "$(basename "$1")"; }
_gitwo_runtime_port_free() {
  ruby -rsocket -e 'begin; s = TCPServer.new("127.0.0.1", Integer(ARGV.fetch(0))); s.close; rescue SystemCallError; exit 1; end' "$1"
}
_gitwo_runtime_reserved() {
  local candidate="$1" f
  for f in "$GITWO_GLOBAL_STATE_ROOT"/projects/*/runtime/*.ports; do
    [[ -f "$f" ]] || continue
    if grep -Eq "^(REDIS_DEV_PORT|REDIS_TEST_PORT|WEB_PORT)=${candidate}$" "$f"; then return 0; fi
  done
  return 1
}
_gitwo_runtime_allocate_one() {
  local start="$1" end="$2" candidate
  for ((candidate=start; candidate<=end; candidate++)); do
    if ! _gitwo_runtime_reserved "$candidate" && _gitwo_runtime_port_free "$candidate"; then
      printf '%s\n' "$candidate"
      return 0
    fi
  done
  gitwo_die "No free ports in $start-$end"
}
_gitwo_runtime_allocate() (
  # Atomic mkdir lock also works across two concurrent Gitwo terminals.
  local path="$1" root lock ports i a b c
  root="$(_gitwo_runtime_root)"
  mkdir -p "$root" "$GITWO_GLOBAL_STATE_ROOT"; chmod 700 "$root" "$GITWO_GLOBAL_STATE_ROOT"
  ports="$(_gitwo_runtime_ports_file "$path")"
  lock="$GITWO_GLOBAL_STATE_ROOT/.allocate-lock"
  for ((i=0;i<100;i++)); do
    if mkdir "$lock" 2>/dev/null; then break; fi
    sleep 0.1
  done
  [[ -d "$lock" && $i -lt 100 ]] || gitwo_die 'Could not acquire runtime port allocation lock'
  # Only the process that acquired the lock removes it.
  trap 'rmdir "$lock" 2>/dev/null || true' EXIT
  [[ ! -e "$ports" ]] || exit 0
  a="$(_gitwo_runtime_allocate_one 16380 19379)"
  b="$(_gitwo_runtime_allocate_one 19380 22379)"
  c="$(_gitwo_runtime_allocate_one 12000 14999)"
  (umask 077; printf 'REDIS_DEV_PORT=%s\nREDIS_TEST_PORT=%s\nWEB_PORT=%s\n' "$a" "$b" "$c" > "$ports")
)

gitwo_runtime_existing_load() {
  local path="$1" ports
  ports="$(_gitwo_runtime_ports_file "$path")"
  [[ -e "$ports" || -L "$ports" ]] || return 1
  [[ -f "$ports" && ! -L "$ports" ]] || gitwo_die "Unsafe runtime ports file: $ports"
  # File is generated by this tool. Validate exact safe numeric lines before sourcing.
  if [[ "$(wc -l < "$ports" | tr -d ' ')" != 3 ]] || ! grep -Eq '^REDIS_DEV_PORT=[0-9]{4,5}$' "$ports" || ! grep -Eq '^REDIS_TEST_PORT=[0-9]{4,5}$' "$ports" || ! grep -Eq '^WEB_PORT=[0-9]{4,5}$' "$ports"; then
    gitwo_die "Invalid runtime ports file: $ports"
  fi
  # Parse numeric metadata as data. Do not execute a ports file as shell code.
  local key value seen_dev=0 seen_test=0 seen_web=0
  while IFS='=' read -r key value; do
    [[ "$value" =~ ^[0-9]{4,5}$ ]] || gitwo_die "Invalid port in $ports"
    (( value >= 1024 && value <= 65535 )) || gitwo_die "Out-of-range port in $ports"
    case "$key" in
      REDIS_DEV_PORT) REDIS_DEV_PORT="$value"; seen_dev=$((seen_dev + 1)) ;;
      REDIS_TEST_PORT) REDIS_TEST_PORT="$value"; seen_test=$((seen_test + 1)) ;;
      WEB_PORT) WEB_PORT="$value"; seen_web=$((seen_web + 1)) ;;
      *) gitwo_die "Unexpected port key in $ports" ;;
    esac
  done < "$ports"
  [[ "$seen_dev" == 1 && "$seen_test" == 1 && "$seen_web" == 1 ]] ||
    gitwo_die "Missing or duplicate runtime port key in $ports"
  [[ "$REDIS_DEV_PORT" != "$REDIS_TEST_PORT" && "$REDIS_DEV_PORT" != "$WEB_PORT" && "$REDIS_TEST_PORT" != "$WEB_PORT" ]] || gitwo_die 'Overlapping runtime ports'
}
gitwo_runtime_load() {
  _gitwo_runtime_allocate "$1"
  gitwo_runtime_existing_load "$1" || gitwo_die "Missing runtime ports for $(basename "$1")"
}
_gitwo_redis_port() { if [[ "$1" == development ]]; then printf '%s\n' "$REDIS_DEV_PORT"; else printf '%s\n' "$REDIS_TEST_PORT"; fi; }
gitwo_redis_url() { printf 'redis://127.0.0.1:%s/0\n' "$(_gitwo_redis_port "$1")"; }
_gitwo_redis_cli() { redis-cli -h 127.0.0.1 -p "$1" --raw "$2" "${@:3}"; }
# Ownership is checked using an owned pidfile and Redis's actual process_id.
# Do not use a Redis key as an ownership marker: Rails.cache.clear or FLUSHALL
# could erase it while the process is still ours.
_gitwo_redis_is_owned() {
  local path="$1" mode="$2" port="$3" pidfile pid actual cmd
  pidfile="$(_gitwo_runtime_dir "$path")/redis-${mode}.pid"
  [[ -f "$pidfile" && ! -L "$pidfile" ]] || return 1
  pid="$(cat "$pidfile")"
  [[ "$pid" =~ ^[0-9]+$ ]] || return 1
  actual="$(_gitwo_redis_cli "$port" INFO server 2>/dev/null | awk -F: '/^process_id:/ {gsub(/\r/, "", $2); print $2; exit}')"
  [[ "$pid" == "$actual" ]] || return 1
  cmd="$(ps -p "$pid" -o command= 2>/dev/null || true)"
  [[ "$cmd" == *redis-server* ]] || return 1
}

gitwo_redis_start() {
  local path="$1" mode="$2" port dir pidfile i
  [[ "$mode" == development || "$mode" == test ]] || gitwo_die 'Redis mode must be development/test'
  if [[ "$GITWO_SERVICES_BACKEND" == compose ]]; then
    gitwo_compose_up "$path"
    return 0
  fi
  gitwo_need redis-server; gitwo_need redis-cli
  gitwo_runtime_load "$path"
  port="$(_gitwo_redis_port "$mode")"
  dir="$(_gitwo_runtime_dir "$path")"
  mkdir -p "$dir"; chmod 700 "$dir"
  pidfile="$dir/redis-${mode}.pid"
  if [[ "$(_gitwo_redis_cli "$port" PING 2>/dev/null || true)" == PONG ]]; then
    _gitwo_redis_is_owned "$path" "$mode" "$port" || gitwo_die "Port $port is a Redis process NOT owned by this workspace. Refusing to reuse it."
    return 0
  fi
  _gitwo_runtime_port_free "$port" || gitwo_die "Redis port $port is busy with another service"
  redis-server --bind 127.0.0.1 --protected-mode yes --port "$port" \
    --daemonize yes --pidfile "$pidfile" --logfile "$dir/redis-${mode}.log" \
    --dir "$dir" --save '' --appendonly no --databases 1 >/dev/null || gitwo_die "Cannot start Redis on port $port"
  for ((i=0;i<40;i++)); do
    if [[ "$(_gitwo_redis_cli "$port" PING 2>/dev/null || true)" == PONG ]]; then break; fi
    sleep 0.1
  done
  _gitwo_redis_is_owned "$path" "$mode" "$port" || gitwo_die "Redis did not become healthy and owned on port $port"
  gitwo_ok "Redis ${mode} started on 127.0.0.1:$port"
}

gitwo_redis_stop() {
  local path="$1" mode="$2" port
  if [[ "$GITWO_SERVICES_BACKEND" == compose ]]; then
    gitwo_compose_down "$path"
    return 0
  fi
  if ! gitwo_runtime_existing_load "$path"; then
    gitwo_log "Redis $mode: no allocated ports"
    return 0
  fi
  port="$(_gitwo_redis_port "$mode")"
  if [[ "$(_gitwo_redis_cli "$port" PING 2>/dev/null || true)" != PONG ]]; then
    gitwo_log "Redis $mode is not running on $port"
    return 0
  fi
  _gitwo_redis_is_owned "$path" "$mode" "$port" || gitwo_die "Refusing to stop Redis on $port: process is not owned by this workspace"
  _gitwo_redis_cli "$port" SHUTDOWN NOSAVE >/dev/null 2>&1 || true
  gitwo_ok "Redis $mode stopped on port $port"
}

# Runtime variables must be exported for the existing Sidekiq and Rails clients.
gitwo_runtime_environment() {
  local path="$1" mode="$2" url
  gitwo_redis_start "$path" "$mode"
  url="$(gitwo_redis_url "$mode")"
  export REDIS_URL="$url" SIDEKIQ_REDIS_URL="$url" GITWO_REDIS_URL="$url"
}

gitwo_web_name() { printf '%s.%s\n' "$(basename "$1")" "${GITWO_DOMAIN:-$(basename "$GITWO_SOURCE")}"; }
gitwo_web_url() { printf 'https://%s.localhost\n' "$(gitwo_web_name "$1")"; }
