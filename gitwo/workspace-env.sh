#!/usr/bin/env bash
# Explicit setup and verification of per-workspace direnv activation.
set -euo pipefail
source "$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)/_common.sh"
source "$GITWO_DIR/_runtime.sh"

usage() {
  cat <<'USAGE'
Usage: gitwo workspace env <init|verify> [WORKSPACE]
       gitwo workspace env integrate [--dry-run|--apply]
  init     Verify native Rails DB isolation and create an ignored .envrc
  verify   Check existing Rails DB targets without reserving ports or starting Redis
  integrate  Preview or explicitly update simple tracked config/database.yml

Setup direnv in your shell, then review and approve the generated .envrc:
  eval "$(direnv hook zsh)"  # Add this once to ~/.zshrc (bash: direnv hook bash)
  direnv allow .

Gitwo never auto-approves .envrc, overwrites a tracked .envrc, or edits database.yml.
USAGE
}

[[ "${1:-}" != -h && "${1:-}" != --help ]] || { usage; exit 0; }
[[ $# -ge 1 ]] || { usage >&2; exit 2; }
action="$1"; shift
case "$action" in
  integrate)
    [[ $# -le 1 ]] || { usage >&2; exit 2; }
    mode=plan
    case "${1:---dry-run}" in
      --dry-run) ;;
      --apply) mode=apply ;;
      *) usage >&2; exit 2 ;;
    esac
    config="$GITWO_SOURCE/config/database.yml"
    [[ -f "$config" && ! -L "$config" ]] || gitwo_die 'Expected a regular config/database.yml in the primary checkout'
    git -C "$GITWO_SOURCE" ls-files --error-unmatch -- config/database.yml >/dev/null 2>&1 || gitwo_die 'database.yml must be tracked before integration'
    if [[ "$mode" == apply ]]; then
      [[ -z "$(git -C "$GITWO_SOURCE" status --porcelain -- config/database.yml)" ]] || gitwo_die 'database.yml has local changes; commit or stash them before --apply'
    fi
    exec ruby "$GITWO_DIR/rails-config.rb" "$mode" "$config" "$GITWO_STATE/backups"
    ;;
  init|verify)
    [[ $# -le 1 ]] || { usage >&2; exit 2; }
    selector="${1:-}"
    ;;
  *) usage >&2; exit 2 ;;
esac

gitwo_check_source
target="$(gitwo_resolve_path "$selector")"
target="$(cd -- "$target" && pwd -P)"
branch="$(git -C "$target" branch --show-current)"
gitwo_verify_target "$target" "$branch"
gitwo_validate_workspace_identity "$target" "$branch"
gitwo_load_state "$target"
marker="$GITWO_STATE/$(basename "$target").db-ready"
[[ -f "$marker" && ! -L "$marker" && "$(cat "$marker")" == "$GITWO_DB_DEV" ]] || gitwo_die 'Workspace database has not been registered; run gitwo setup first'
[[ -f "$GITWO_STATE/$(basename "$target").bootstrap-status" && "$(cat "$GITWO_STATE/$(basename "$target").bootstrap-status")" == ready ]] || gitwo_die 'Workspace database bootstrap is not ready'
gitwo_db_settings

# verify must never allocate ports or start Redis. A missing allocation is
# reported as a preparation problem rather than being silently repaired.
if [[ "$action" == init ]]; then
  gitwo_runtime_load "$target"
  if [[ "${GITWO_HAS_REDIS:-false}" == true ]]; then
    gitwo_redis_start "$target" development
    gitwo_redis_start "$target" test
  fi
else
  gitwo_runtime_existing_load "$target" || gitwo_die 'No runtime port reservation. Run gitwo workspace env init explicitly.'
fi

# Check database.yml in the normal shell environment. Never use gitwo_rails:
# that wrapper injects DATABASE_URL and would conceal unsafe native commands.
(
  cd "$target"
  source "$GITWO_DIR/direnv.sh"
  gitwo_need mise
  gitwo_ruby_version "$target"
  GITWO_EXPECTED_DB="$GITWO_DB_DEV" \
    mise exec "ruby@$GITWO_RUBY_VERSION" -- bundle exec rails runner \
    'abort "Gitwo: native development DB is not isolated" unless ActiveRecord::Base.connection_db_config.database == ENV.fetch("GITWO_EXPECTED_DB")' >/dev/null
  RAILS_ENV=test GITWO_EXPECTED_DB="$GITWO_DB_TEST" \
    mise exec "ruby@$GITWO_RUBY_VERSION" -- bundle exec rails runner \
    'abort "Gitwo: native test DB is not isolated" unless ActiveRecord::Base.connection_db_config.database == ENV.fetch("GITWO_EXPECTED_DB")' >/dev/null
) || gitwo_die 'Native Rails DB verification failed. Run gitwo workspace env integrate --dry-run in the primary checkout; no .envrc was written.'

gitwo_ok "Native Rails development/test DB targets verified: $(basename "$target")"
[[ "$action" == init ]] || exit 0

envrc="$target/.envrc"
source_file="$GITWO_DIR/direnv.sh"
[[ -f "$source_file" && ! -L "$source_file" ]] || gitwo_die 'Missing safe Gitwo direnv loader'
printf -v quoted_source '%q' "$source_file"
printf -v quoted_workspace '%q' "$target"
contents="# Generated by Gitwo. Review and approve once using: direnv allow .
# Gitwo does not run or trust arbitrary .envrc files.
# source_env can evaluate outside this directory, so preserve the exact workspace.
export GITWO_DIRENV_WORKSPACE=$quoted_workspace
source_env $quoted_source
"
if [[ -e "$envrc" || -L "$envrc" ]]; then
  if [[ -f "$envrc" && ! -L "$envrc" && "$(cat "$envrc")" == "${contents%$'\n'}" ]]; then
    gitwo_ok 'Existing managed .envrc verified; no changes'
    exit 0
  fi
  gitwo_warn 'Existing .envrc belongs to the application or developer; refusing to overwrite.'
  printf '  To integrate manually, add: source_env %s\n' "$quoted_source" >&2
  exit 0
fi

# Add one precise, local ignore pattern to the shared Git info/exclude.
# This does not change the repository index or committed .gitignore.
git_common="$(git -C "$target" rev-parse --git-common-dir)"
[[ "$git_common" == /* ]] || git_common="$target/$git_common"
exclude="$git_common/info/exclude"
[[ ! -L "$exclude" && ( ! -e "$exclude" || -f "$exclude" ) ]] || gitwo_die 'Unsafe Git exclude file'
mkdir -p "$(dirname "$exclude")"
if [[ ! -f "$exclude" ]] || ! grep -qxF '/.envrc' "$exclude"; then
  printf '\n# Local Gitwo direnv activation (untracked worktrees)\n/.envrc\n' >> "$exclude"
fi
# Refuse replacement if another process created the file during verification.
(umask 077; set -C; printf '%s' "$contents" > "$envrc") || gitwo_die 'Refusing to replace existing .envrc'
gitwo_ok "Created local .envrc for $target"
if command -v direnv >/dev/null 2>&1; then
  gitwo_log "Run: cd '$target' && direnv allow ."
else
  gitwo_warn 'direnv not installed. Install direnv and add its shell hook, then run direnv allow .'
fi
